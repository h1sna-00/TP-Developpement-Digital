mois = int(input("Numéro du mois : "))

if mois == 1:
    print("janvier")
elif mois == 2:
    print("février")
elif mois == 3:
    print("mars")
elif mois == 4:
    print("avril")
elif mois == 5:
    print("mai")
elif mois == 6:
    print("juin")
elif mois == 7:
    print("juillet")
elif mois == 8:
    print("août")
elif mois == 9:
    print("septembre")
elif mois == 10:
    print("octobre")
elif mois == 11:
    print("novembre")
elif mois == 12:
    print("décembre")
else:
    print("Erreur, tapez un numéro entre 1 et 12")